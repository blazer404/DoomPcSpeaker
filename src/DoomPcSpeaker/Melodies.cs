    public static readonly Song[] All = Groups.SelectMany(g => g.Tracks).ToArray();

    public static Song? Resolve(string query)
    {
        var q = query.Trim();
        if (q.Length == 0) return null;

        if (IsRandom(q))
            return All[Random.Shared.Next(All.Length)];

        if (int.TryParse(q, out int n) && n >= 1 && n <= All.Length)
            return All[n - 1];

        var exact = All.FirstOrDefault(s => s.Key.Equals(q, StringComparison.OrdinalIgnoreCase));
        if (exact is not null) return exact;

        return All.FirstOrDefault(s =>
            s.Key.Contains(q, StringComparison.OrdinalIgnoreCase) ||
            s.Name.Contains(q, StringComparison.OrdinalIgnoreCase));
    }

    private static bool IsRandom(string q) =>
        q.Equals("random", StringComparison.OrdinalIgnoreCase) ||
        q.Equals("r", StringComparison.OrdinalIgnoreCase);
